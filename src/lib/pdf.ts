import { PDFDocument, StandardFonts, rgb, PDFName } from "pdf-lib";
import { generateBarcodeBuffer } from "./barcode";
import { generateQRCodeBuffer } from "./qrcode";

interface JobCardData {
  jobNumber: string;
  customerName: string;
  poNumber?: string;
  drawingNumber?: string;
  material?: string;
  grade?: string;
  quantity: number;
  unit: string;
  dueDate?: string;
  priority: string;
  status: string;
  remarks?: string;
}

interface DispatchChallanData {
  dispatchNumber: string;
  jobNumber: string;
  customerName: string;
  quantityDispatched: number;
  vehicleNumber?: string;
  transporterName?: string;
  lrNumber?: string;
  driverName?: string;
  driverPhone?: string;
  invoiceNumber?: string;
  invoiceAmount?: number;
  dispatchDate: string;
}

interface DeliveryReceiptData {
  dispatchNumber: string;
  jobNumber: string;
  customerName: string;
  quantityDispatched: number;
  deliveredAt: string;
  deliveredBy?: string;
}

// Create job card PDF
export async function generateJobCardPDF(data: JobCardData): Promise<Buffer> {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([595.28, 841.89]); // A4
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  // Header
  page.drawText("JOB TRACK PRO", {
    x: 50,
    y: 800,
    size: 24,
    font: boldFont,
    color: rgb(0.1, 0.2, 0.35),
  });

  page.drawText("JOB CARD", {
    x: 50,
    y: 770,
    size: 16,
    font: boldFont,
    color: rgb(0.2, 0.4, 0.7),
  });

  // Barcode
  try {
    const barcodeBuffer = await generateBarcodeBuffer(data.jobNumber, { height: 30 });
    const barcodeImage = await pdfDoc.embedPng(barcodeBuffer);
    page.drawImage(barcodeImage, { x: 50, y: 720, width: 200, height: 40 });
  } catch {
    page.drawText(`Barcode: ${data.jobNumber}`, { x: 50, y: 730, size: 10, font });
  }

  // QR Code
  try {
    const qrBuffer = await generateQRCodeBuffer(`${process.env.FRONTEND_URL || "http://localhost:3000"}/track/${data.jobNumber}`, { width: 100 });
    const qrImage = await pdfDoc.embedPng(qrBuffer);
    page.drawImage(qrImage, { x: 450, y: 720, width: 100, height: 100 });
  } catch {
    // QR code optional
  }

  // Job details
  let y = 680;
  const lineHeight = 25;

  const details = [
    ["Job Number", data.jobNumber],
    ["Customer", data.customerName],
    ["PO Number", data.poNumber || "-"],
    ["Drawing No.", data.drawingNumber || "-"],
    ["Material", data.material || "-"],
    ["Grade", data.grade || "-"],
    ["Quantity", `${data.quantity} ${data.unit}`],
    ["Priority", data.priority],
    ["Status", data.status.replace(/_/g, " ").toUpperCase()],
    ["Due Date", data.dueDate || "-"],
    ["Remarks", data.remarks || "-"],
  ];

  for (const [label, value] of details) {
    page.drawText(`${label}:`, { x: 50, y, size: 11, font: boldFont });
    page.drawText(String(value), { x: 180, y, size: 11, font });
    y -= lineHeight;
  }

  // Footer
  page.drawText("Generated by JobTrack Pro", {
    x: 50,
    y: 50,
    size: 8,
    font,
    color: rgb(0.5, 0.5, 0.5),
  });

  page.drawText(new Date().toLocaleDateString(), {
    x: 450,
    y: 50,
    size: 8,
    font,
    color: rgb(0.5, 0.5, 0.5),
  });

  return Buffer.from(await pdfDoc.save());
}

// Create dispatch challan PDF
export async function generateDispatchChallanPDF(data: DispatchChallanData): Promise<Buffer> {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([595.28, 841.89]);
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  // Header
  page.drawText("DISPATCH CHALLAN", {
    x: 200,
    y: 800,
    size: 20,
    font: boldFont,
    color: rgb(0.1, 0.2, 0.35),
  });

  page.drawText(`Dispatch No: ${data.dispatchNumber}`, {
    x: 50,
    y: 760,
    size: 12,
    font: boldFont,
  });

  page.drawText(`Date: ${data.dispatchDate}`, {
    x: 400,
    y: 760,
    size: 12,
    font,
  });

  // Horizontal line
  page.drawLine({
    start: { x: 50, y: 750 },
    end: { x: 545, y: 750 },
    thickness: 1,
    color: rgb(0, 0, 0),
  });

  // Job details
  let y = 720;
  const jobDetails = [
    ["Job Number", data.jobNumber],
    ["Customer", data.customerName],
    ["Quantity Dispatched", String(data.quantityDispatched)],
    ["Vehicle Number", data.vehicleNumber || "-"],
    ["Transporter", data.transporterName || "-"],
    ["L.R. Number", data.lrNumber || "-"],
    ["Driver Name", data.driverName || "-"],
    ["Driver Phone", data.driverPhone || "-"],
    ["Invoice Number", data.invoiceNumber || "-"],
    ["Invoice Amount", data.invoiceAmount ? `₹${data.invoiceAmount.toLocaleString()}` : "-"],
  ];

  for (const [label, value] of jobDetails) {
    page.drawText(`${label}:`, { x: 50, y, size: 11, font: boldFont });
    page.drawText(String(value), { x: 200, y, size: 11, font });
    y -= 22;
  }

  // Signature lines
  y = 200;
  page.drawText("Authorized Signature", { x: 50, y, size: 10, font });
  page.drawLine({
    start: { x: 50, y: y - 5 },
    end: { x: 200, y: y - 5 },
    thickness: 0.5,
  });

  page.drawText("Receiver's Signature", { x: 350, y, size: 10, font });
  page.drawLine({
    start: { x: 350, y: y - 5 },
    end: { x: 500, y: y - 5 },
    thickness: 0.5,
  });

  return Buffer.from(await pdfDoc.save());
}

