// Create invoice template PDF
export async function generateInvoicePDF(data: {
  invoiceNumber: string;
  invoiceDate: string;
  jobNumber: string;
  customerName: string;
  customerAddress?: string;
  items: Array<{ description: string; quantity: number; rate: number; amount: number }>;
  totalAmount: number;
  taxAmount?: number;
  grandTotal: number;
}): Promise<Buffer> {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([595.28, 841.89]);
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  // Header
  page.drawText("TAX INVOICE", {
    x: 220,
    y: 800,
    size: 22,
    font: boldFont,
    color: rgb(0.1, 0.2, 0.35),
  });

  // Invoice details
  let y = 760;
  page.drawText(`Invoice No: ${data.invoiceNumber}`, { x: 50, y, size: 11, font: boldFont });
  page.drawText(`Date: ${data.invoiceDate}`, { x: 350, y, size: 11, font });
  page.drawText(`Job No: ${data.jobNumber}`, { x: 50, y: y - 20, size: 11, font });

  // Customer info
  y = 700;
  page.drawText("Bill To:", { x: 50, y, size: 11, font: boldFont });
  page.drawText(data.customerName, { x: 50, y: y - 20, size: 11, font });
  if (data.customerAddress) {
    page.drawText(data.customerAddress, { x: 50, y: y - 40, size: 10, font });
  }

  // Table header
  y = 620;
  page.drawText("Description", { x: 50, y, size: 10, font: boldFont });
  page.drawText("Qty", { x: 300, y, size: 10, font: boldFont });
  page.drawText("Rate", { x: 370, y, size: 10, font: boldFont });
  page.drawText("Amount", { x: 460, y, size: 10, font: boldFont });

  page.drawLine({
    start: { x: 50, y: y - 5 },
    end: { x: 545, y: y - 5 },
    thickness: 0.5,
  });

  // Items
  y -= 25;
  for (const item of data.items) {
    page.drawText(item.description, { x: 50, y, size: 10, font });
    page.drawText(String(item.quantity), { x: 300, y, size: 10, font });
    page.drawText(`₹${item.rate.toLocaleString()}`, { x: 370, y, size: 10, font });
    page.drawText(`₹${item.amount.toLocaleString()}`, { x: 460, y, size: 10, font });
    y -= 20;
  }

  // Totals
  y -= 20;
  page.drawLine({
    start: { x: 350, y: y + 10 },
    end: { x: 545, y: y + 10 },
    thickness: 0.5,
  });

  page.drawText("Subtotal:", { x: 370, y, size: 10, font: boldFont });
  page.drawText(`₹${data.totalAmount.toLocaleString()}`, { x: 460, y, size: 10, font });

  if (data.taxAmount) {
    y -= 20;
    page.drawText("Tax:", { x: 370, y, size: 10, font: boldFont });
    page.drawText(`₹${data.taxAmount.toLocaleString()}`, { x: 460, y, size: 10, font });
  }

  y -= 25;
  page.drawText("Grand Total:", { x: 370, y, size: 12, font: boldFont });
  page.drawText(`₹${data.grandTotal.toLocaleString()}`, { x: 450, y, size: 12, font: boldFont });

  // Footer
  page.drawText("Thank you for your business!", {
    x: 200,
    y: 100,
    size: 12,
    font,
    color: rgb(0.2, 0.4, 0.7),
  });

  return Buffer.from(await pdfDoc.save());
}
